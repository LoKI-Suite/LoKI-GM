function lines = l0_setup_text(c, mode)
% L0_SETUP_TEXT  Setup-file lines for case c of l0_cases() in a given grid mode.
%
%   mode = 'ref'      reference code (e.g. master): uniform grid, no VEG keys
%          'uniform'  branch 14 on a uniform grid (variableGrid false, discrete operators on)
%          'veg'      branch 14 on the geometric variable grid

  onOff = {'false', 'true'};

  switch mode
    case 'ref'
      gridKeys = {};
    case 'uniform'
      gridKeys = {
        '      inelCollisions: true'
        '      variableGrid: false'
        };
    case 'veg'
      firstStep = 1e-3;
      if isfield(c, 'grid') && isfield(c.grid, 'firstEnergyStep')
        firstStep = c.grid.firstEnergyStep;
      end
      gridKeys = {
        '      inelCollisions: true'
        '      variableGrid: true'
        sprintf('      firstEnergyStep: %.15g', firstStep)
        };
    otherwise
      error('l0_setup_text:mode', 'Unknown mode "%s" (use ref, uniform or veg).', mode);
  end

  % ODE options suggested in the default setup for the temporalIntegration algorithm
  odeLines = {};
  if strcmp(c.algorithm, 'temporalIntegration')
    odeLines = {
      '      odeSetParameters:'
      '        AbsTol: 1e-300'
      '        RelTol: 1e-6'
      '        MaxStep: 1e-7'
      };
  end

  % energy-grid size: smart grid with 200 cells (L0) or a fixed grid (l0_refine)
  if isfield(c, 'grid') && ~isempty(c.grid)
    sizeKeys = {
      sprintf('      maxEnergy: %.15g', c.grid.maxEnergy)
      sprintf('      cellNumber: %d', c.grid.cellNumber)
      };
  else
    sizeKeys = {
      '      maxEnergy: 20'
      '      cellNumber: 200'
      '      smartGrid:'
      '        minEedfDecay: 20'
      '        maxEedfDecay: 25'
      '        updateFactor: 0.05'
      };
  end

  lines = [
    {
    '% Generated by Benchmarking/L0/l0_setup_text.m - do not edit'
    'workingConditions:'
    ['  reducedField: ' c.reducedField]
    '  electronTemperature: 1'
    ['  excitationFrequency: ' num2str(c.excFreq)]
    '  gasPressure: 133.32'
    '  gasTemperature: 300'
    '  wallTemperature: 300'
    '  extTemperature: 300'
    '  surfaceSiteDensity: 1e19'
    '  electronDensity: 1e19'
    '  chamberLength: 1.0'
    '  chamberRadius: 1.0'
    'electronKinetics:'
    '  isOn: true'
    '  eedfType: boltzmann'
    ['  ionizationOperatorType: ' c.ionType]
    ['  growthModelType: ' c.growth]
    ['  includeEECollisions: ' onOff{c.ee+1}]
    }
    c.gasBlock
    {
    '  numerics:'
    '    energyGrid:'
    }
    gridKeys
    sizeKeys
    {
    '    maxPowerBalanceRelError: 1e-9'
    '    nonLinearRoutines:'
    ['      algorithm: ' c.algorithm]
    '      mixingParameter: 0.7'
    '      maxEedfRelError: 1e-9'
    }
    odeLines
    {
    'gui:'
    '  isOn: false'
    '  refreshFrequency: 1'
    'output:'
    '  isOn: false'
    }
    ];

end
