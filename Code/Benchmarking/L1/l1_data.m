function out = l1_data(action)
% L1_DATA  Cross-section files of the L1 harness.
%
%   c = l1_data('constantNu')   sigma*sqrt(u) (m^2 eV^0.5) of the constant-nu elastic cross section
%   l1_data('write')            writes Output/L1/data/H2_constant_nu.txt and H2_elastic.txt
%                               (current folder: Code folder of the tree under test)
%
% H2_elastic.txt: the ELASTIC block of Input/Hydrogen/H2_LXCat.txt, unchanged (real H2 data, D-011).
%
% H2_constant_nu.txt: sigma(u) = c/sqrt(u), i.e. sigma proportional to 1/v and a constant collision
% frequency nu/N = c*sqrt(2e/me) (5.9e-14 m^3/s). c = 1e-19 m^2 eV^0.5 (sigma = 1e-19 m^2 at 1 eV).
% LoKI interpolates the table linearly at the grid nodes, so the table is dense (20001 log-spaced
% points from 1e-7 to 1e3 eV): the relative interpolation error of c/sqrt(u) is ~1e-7, below the
% discretisation errors measured by L1. Below 1e-7 eV LoKI would use 0; the smallest non-zero node
% of the L1 grids is larger.

  c = 1e-19;

  switch action
    case 'constantNu'
      out = c;

    case 'write'
      dataDir = fullfile('Output', 'L1', 'data');
      if ~isfolder(dataDir), mkdir(dataDir); end

      % constant collision frequency
      u = logspace(-7, 3, 20001);
      fid = fopen(fullfile(dataDir, 'H2_constant_nu.txt'), 'w');
      fprintf(fid, 'L1 test cross section, generated by Benchmarking/L1/l1_data.m - do not edit\n\n');
      fprintf(fid, 'ELASTIC\nH2\n 2.743480e-4\nSPECIES: e / H2\n');
      fprintf(fid, 'PROCESS: E + H2 -> E + H2, Elastic\n');
      fprintf(fid, 'PARAM.:  sigma = c/sqrt(u), c = %.6e m2 eV^0.5 (constant collision frequency)\n', c);
      fprintf(fid, 'COMMENT: [e + H2(X) -> e + H2(X), Elastic] synthetic, sigma proportional to 1/v\n');
      fprintf(fid, 'COLUMNS: Energy (eV) | Cross section (m2)\n-----------------------------\n');
      fprintf(fid, ' %.12e\t%.12e\n', [u; c./sqrt(u)]);
      fprintf(fid, '-----------------------------\n');
      fclose(fid);

      % real H2 elastic cross section
      src = readlines(fullfile('Input', 'Hydrogen', 'H2_LXCat.txt'));
      i0 = find(strtrim(src) == "ELASTIC", 1);
      dashes = find(startsWith(src, '-----'));
      dashes = dashes(dashes > i0);
      if isempty(i0) || numel(dashes) < 2
        error('l1_data:H2', 'ELASTIC block not found in Input/Hydrogen/H2_LXCat.txt');
      end
      block = [ "L1 test file, generated by Benchmarking/L1/l1_data.m from Input/Hydrogen/H2_LXCat.txt - do not edit"
                ""
                src(i0:dashes(2)) ];
      writelines(block, fullfile(dataDir, 'H2_elastic.txt'));
      out = dataDir;

    otherwise
      error('l1_data:action', 'Unknown action "%s".', action);
  end

end
